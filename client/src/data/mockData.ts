// Helper for generating realistic 24-hour time series
function generateSeries(base: number, variance: number, trend: number = 0): TimeSeriesPoint[] {
  const times = [
    "00:00", "02:00", "04:00", "06:00", "08:00", "10:00",
    "12:00", "14:00", "16:00", "18:00", "20:00", "22:00"
  ];
  return times.map((t, idx) => {
    const raw = base + (Math.sin(idx * 0.8) * variance) + (idx * trend * 0.1);
    const rounded = Math.round(raw * 10) / 10;
    return {
      time: t,
      value: Math.max(0, rounded),
    };
  });
}

